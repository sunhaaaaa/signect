FALLBACK_TOPIC = "기타"

# Sino-Korean numeral/currency words (영,일,이,삼…만,억,조, optionally with a
# leading digit prefix like "10만원"). The WORD dataset carries these as
# plain vocabulary entries distinct from the finger-counting 지숫자 category.
NUM_RE = re.compile(r"^[0-9]*[영일이삼사오육칠팔구십백천만억조]+[0-9]*원?$")


def classify(label: str) -> str:
    # Explicit exact overrides win first — e.g. '팔' is both the digit 8 and
    # the body part "arm"; EXACT_RULES' curated call beats the generic regex.
    for topic, keywords in EXACT_RULES:
        if label in keywords:
            return topic
    if NUM_RE.match(label):
        return "숫자·수량"
    for topic, keywords in RULES:
        for kw in keywords:
            if kw in label:
                return topic
    # Catch-all: most remaining unclassified labels are plain verbs/adjectives
    # (동작·묘사 already covers this pattern extensively above).
    if len(label) > 1 and label.endswith("다"):
        return "동작·묘사"
    return FALLBACK_TOPIC


def main():
    with open(IN_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    counts = {}
    for entry in data:
        if entry.get("category") != "word":
            continue
        topic = classify(entry["label"])
        entry["topic"] = topic
        counts[topic] = counts.get(topic, 0) + 1

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

    total_labels = len({e["label"] for e in data if e.get("category") == "word"})
    print(f"unique word labels: {total_labels}")
    for topic, count in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"  {topic}: {count // 2}")  # /2 because each label has an original + mirror entry


if __name__ == "__main__":
    main()
