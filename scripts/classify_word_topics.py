FALLBACK_TOPIC = "기타"


def classify(label: str) -> str:
    for topic, keywords in RULES:
        for kw in keywords:
            if kw in label:
                return topic
    return FALLBACK_TOPIC


def main():
    with open(IN_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    counts = {}
    for entry in data:
        if entry.get("category") != "word":
            continue
        topic = classify(entry["label"])
        entry["topic"] = topic
        counts[topic] = counts.get(topic, 0) + 1

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

    total_labels = len({e["label"] for e in data if e.get("category") == "word"})
    print(f"unique word labels: {total_labels}")
    for topic, count in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"  {topic}: {count // 2}")  # /2 because each label has an original + mirror entry


if __name__ == "__main__":
    main()
